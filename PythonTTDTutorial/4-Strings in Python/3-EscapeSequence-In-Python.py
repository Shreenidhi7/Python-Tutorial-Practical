# \n => new/next line
# \t => tab
# \\ => backslash
# \' => inserts a single quote inside a single quoted string

# 1. \n [Slash newline]
print("Hello Everyone.\nHow are you doing?")

# 2. \t [Slash tab]
print("Shree 20")
print("Shree\t20")

# 3. \\ [Double Slash]
# print("new\old")
print("new\\old")

print("yes\no")
print("yes\\no")

# 4. \' [Single Quoted Backslash]
# print('This is python's lecture')
print('This is python\'s lecture')

# 5. \" [Double Quoted Backslash
# print("This is python"s lecture")
print("This is python\"s lecture")
# print("He says, "We are learning python"")
print("He says, \"We are leaning python\" ")